CREATE TABLE IF NOT EXISTS games (id TEXT PRIMARY KEY, title TEXT, author TEXT, blurb TEXT, code TEXT, at INTEGER);
CREATE TABLE IF NOT EXISTS requests (id TEXT PRIMARY KEY, title TEXT, author TEXT, blurb TEXT, code TEXT, at INTEGER);
CREATE TABLE IF NOT EXISTS rl (key TEXT, at INTEGER);
CREATE INDEX IF NOT EXISTS rl_key ON rl(key, at);
CREATE TABLE IF NOT EXISTS settings (k TEXT PRIMARY KEY, v TEXT);
